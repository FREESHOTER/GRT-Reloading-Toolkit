    private static IReadOnlyList<ShotSample> Shots((int S, double V, double Cw, double Bto, double Pw)[] rows) =>
        rows.Select(r => new ShotSample(r.S, r.V, new Dictionary<string, double>
        { ["case_weight_gr"] = r.Cw, ["bullet_bto_mm"] = r.Bto, ["powder_weight_gr"] = r.Pw })).ToList();

    private static IReadOnlyList<CartridgeInput> Lot((int N, double? Cw, double Bto, bool Out)[] rows) =>
        rows.Select(r =>
        {
            var m = new Dictionary<string, double> { ["bullet_bto_mm"] = r.Bto, ["powder_weight_gr"] = 40.30 };
            if (r.Cw is { } cw) m["case_weight_gr"] = cw;
            return new CartridgeInput(r.N, "", m, r.Out);
        }).ToList();

    private static void Near(double expected, double actual, double tol = 1e-6) =>
        Assert.True(Math.Abs(expected - actual) <= tol * Math.Max(1, Math.Abs(expected)), $"expected {expected}, got {actual}");

    private static void CheckModel(T[] tested, string[] sig, T[] sigTerms, int n, int nSeries, double sdWithin, double r2, double sdResid,
        (double R, int N, double Without, double With)? loo, VelocityModelResult m)
    {
        Assert.Equal(n, m.NShots);
        Assert.Equal(nSeries, m.NSeries);
        Near(sdWithin, m.SdWithin); Near(r2, m.R2); Near(sdResid, m.SdResidual);
        Assert.Equal(tested.Select(t => t.Key), m.Tested.Select(t => t.Key));          // same order: by p
        for (int i = 0; i < tested.Length; i++)
        {
            var e = tested[i]; var a = m.Tested[i];
            Assert.Equal(e.N, a.N); Assert.Equal(e.Series, a.Series);
            Near(e.R, a.R); Near(e.P, a.P); Near(e.PAdj, a.PAdj);
            Assert.Equal(e.Sig, a.Significant);
        }
        Assert.Equal(sig, m.Significant.Select(t => t.Key).ToArray());
        foreach (var e in sigTerms)
        {
            var a = m.Significant.Single(t => t.Key == e.Key);
            Near(e.Slope, a.Slope); Near(e.Se, a.Se); Near(e.SdX, a.SdX); Near(e.SdFrom, a.SdFrom);
        }
        if (loo is null) Assert.Null(m.LeaveOneOut);
        else
        {
            Assert.NotNull(m.LeaveOneOut);
            Near(loo.Value.R, m.LeaveOneOut!.R); Assert.Equal(loo.Value.N, m.LeaveOneOut.N);
            Near(loo.Value.Without, m.LeaveOneOut.SdWithout); Near(loo.Value.With, m.LeaveOneOut.SdWith);
        }
    }

