        ("toolkit-loadsheet", "Toolkit — Load sheet (recipe + cost)"),
    };

    /// <summary>The GRT install root (parent of <c>doku/</c>), inferred from the running exe.</summary>
    public static string? InferGrtRoot()
    {
        // exe lives in <root>/plugins/ReloadingToolkit/
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        for (int up = 0; up < 5 && dir != null; up++, dir = dir.Parent)
            if (Directory.Exists(Path.Combine(dir.FullName, "doku")))
                return dir.FullName;
        return null;
    }

    /// <summary>Writes the report pages into every <c>doku/&lt;lang&gt;/report</c> folder. Returns a log.</summary>
    public static List<string> Install(string grtRoot)
    {
        var log = new List<string>();
        string doku = Path.Combine(grtRoot, "doku");
        if (!Directory.Exists(doku)) { log.Add($"no doku folder under {grtRoot}"); return log; }

        var enc = new UTF8Encoding(false);
        int langs = 0;
        foreach (var langDir in Directory.GetDirectories(doku))
        {
            string reportDir = Path.Combine(langDir, "report");
            if (!Directory.Exists(reportDir)) continue;
            langs++;
            string lang = Path.GetFileName(langDir);

            foreach (var (name, body) in Pages)
            {
                string path = Path.Combine(reportDir, name + ".txt");
                File.WriteAllText(path, body.Replace("\r\n", "\n").Replace("\n", "\r"), enc);
                log.Add($"{lang}: wrote {name}.txt");
            }

            string startPath = Path.Combine(reportDir, "start.txt");
            if (File.Exists(startPath))
            {
                string start = File.ReadAllText(startPath);
                var missing = Links.Where(l => !start.Contains($"report:{l.Name}", StringComparison.Ordinal)).ToList();
                if (missing.Count == 0)
                    log.Add($"{lang}: start.txt already links all {Links.Length} toolkit reports");
                else
                {
                    var sb = new StringBuilder();
                    foreach (var (name, label) in missing)
                        sb.Append($"  * [[report:{name}|{label}]]\r");
                    // insert after the last existing toolkit link, else after the "default-compact" bullet, else append
                    int anchor = -1;
                    foreach (var l in Links)
                    {
                        int p = start.LastIndexOf($"report:{l.Name}", StringComparison.Ordinal);
                        if (p > anchor) anchor = p;
                    }
                    if (anchor < 0) anchor = start.IndexOf("default-compact", StringComparison.Ordinal);
                    if (anchor >= 0)
                    {
                        int eol = start.IndexOf('\r', anchor);
                        if (eol < 0) eol = start.Length;
                        start = start[..eol] + "\r" + sb.ToString().TrimEnd('\r') + start[eol..];
                    }
                    else start += "\r" + sb;
                    File.WriteAllText(startPath, start, enc);
                    log.Add($"{lang}: added {missing.Count} toolkit link(s) to start.txt");
                }
            }
        }
        log.Add(langs == 0 ? "no report folders found" : $"done — {langs} language folder(s)");
        return log;
    }
