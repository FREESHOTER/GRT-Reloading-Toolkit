    private static readonly (string Name, string Label)[] Links =
    {
        ("toolkit-full", "Toolkit — Full load workup (all sections)"),
        ("toolkit-ocw", "Toolkit — Ladder / OCW report"),
        ("toolkit-seating", "Toolkit — Seating-depth report"),
